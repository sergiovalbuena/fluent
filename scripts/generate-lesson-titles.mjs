#!/usr/bin/env node
// Builds src/lib/lesson-titles.ts from the course files (content/<lang>/*.json):
// each lesson's title in every language it was written in. The app uses it to show
// a lesson's description in the learner's native language.
//
// Usage: node scripts/generate-lesson-titles.mjs   (re-run after adding or editing lessons)

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const titles = {}
for (const lang of readdirSync('content', { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
  for (const file of readdirSync(join('content', lang)).filter(f => /^(lecon|lesson)-\d+\.json$/.test(f)).sort()) {
    const { slug, title } = JSON.parse(readFileSync(join('content', lang, file), 'utf8'))
    if (slug && title && typeof title === 'object') (titles[lang] ??= {})[slug] = title
  }
}

const out = `// Generated by scripts/generate-lesson-titles.mjs from content/<lang>/*.json — do not edit.
// Course language → lesson slug → title in each language.

export const LESSON_TITLES: Record<string, Record<string, Record<string, string>>> = ${JSON.stringify(titles, null, 2)}
`
writeFileSync('src/lib/lesson-titles.ts', out)
console.log(`src/lib/lesson-titles.ts: ${Object.entries(titles).map(([l, t]) => `${l} ${Object.keys(t).length}`).join(', ')}`)
